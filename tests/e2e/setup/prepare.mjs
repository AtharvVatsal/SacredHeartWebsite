// Prepares a clean, disposable database for the end-to-end tests, then builds and starts the site.
// Refuses to run against anything but a local database whose name ends in "_test".
//
//   node tests/e2e/setup/prepare.mjs           (Playwright runs this as its web server)
import { execSync, spawn } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import pg from 'pg'

const ROOT = path.resolve(import.meta.dirname, '../../..')
const PORT = process.env.E2E_PORT || '3300'
const DB = process.env.E2E_DATABASE_URL || 'postgres://postgres@127.0.0.1:54329/shs_cms_test'

const url = new URL(DB)
if (!['127.0.0.1', 'localhost'].includes(url.hostname) || !url.pathname.endsWith('_test')) {
  console.error(`Refusing to reset ${url.hostname}${url.pathname}: the test database must be local and end in _test`)
  process.exit(1)
}

const env = {
  ...process.env,
  DATABASE_URL: DB,
  CMS_SERVER_URL: `http://localhost:${PORT}`,
  CMS_MEDIA_DIR: '.cms/test-media',
  CMS_MEDIA_PERSISTENT_DISK: 'true',
  NODE_OPTIONS: '--no-deprecation',
}
const run = (cmd) => execSync(cmd, { cwd: ROOT, env, stdio: 'inherit' })

// 1. Empty database and media folder
const client = new pg.Client({ connectionString: DB })
await client.connect()
await client.query('DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;')
await client.end()
fs.rmSync(path.join(ROOT, '.cms/test-media'), { recursive: true, force: true })

// 2. Schema, people and the seeded home page draft
run('npx payload migrate')
const creds = {
  admin: { email: 'e2e-admin@example.test', password: crypto.randomBytes(12).toString('base64url'), name: 'Test Administrator' },
  editor: { email: 'e2e-editor@example.test', password: crypto.randomBytes(12).toString('base64url'), name: 'Test Editor' },
  base: `http://localhost:${PORT}`,
}
fs.mkdirSync(path.join(ROOT, 'tests/e2e/.auth'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'tests/e2e/.auth/creds.json'), JSON.stringify(creds, null, 2))
execSync('npx payload run tests/e2e/setup/users.ts', { cwd: ROOT, env: { ...env, E2E_CREDS: JSON.stringify(creds) }, stdio: 'inherit' })
run('npx payload run src/cms/seed/run.ts')
// One small built-in album's photos moved into the media library (the full import takes minutes)
run('npx payload run src/cms/seed/import-gallery.ts notice-board')

// 3. Production build and server (Playwright waits for the port)
if (process.env.E2E_SKIP_BUILD !== 'true') run('npx next build')
else {
  // Reusing a build (debugging only): pages regenerated by an earlier run's publishing live in .next, and must
  // not leak into this run, which starts from an empty database. A full build is the reliable option.
  console.warn('E2E_SKIP_BUILD: reusing the previous build. Run without it for a trustworthy result.')
}
const server = spawn('npx', ['next', 'start', '-p', PORT], { cwd: ROOT, env, stdio: 'inherit', shell: true })
const stop = () => server.kill()
process.on('SIGINT', stop)
process.on('SIGTERM', stop)
